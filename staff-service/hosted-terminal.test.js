import test from 'node:test';
import assert from 'node:assert/strict';
import { getFirestore } from 'firebase-admin/firestore';
import { connectEmulator, provision } from './provider.js';
import { hostedTerminal } from './hosted-terminal.js';

test('two independent verifier clients share one-use tickets and observe portal revocation', async t => {
  assert.equal(process.env.FIRESTORE_EMULATOR_HOST, '127.0.0.1:9180');
  const { auth } = connectEmulator(true);
  const db = getFirestore(auth.app, 'team-staging-test');
  const { Firestore } = await import('@google-cloud/firestore');
  const replica = new Firestore({ projectId: auth.app.options.projectId, databaseId: 'team-staging-test' });
  t.after(() => Promise.all([db.terminate(), replica.terminate()]));
  const portal = hostedTerminal(auth, db, 'https://terminal.example.test');
  const verifier = hostedTerminal(auth, replica);
  const account = await provision({ auth }, { email: 'bridge@example.test', password: 'local-fixture-secret' }, 'board-admin');
  t.after(() => auth.deleteUser(account.uid));
  const cookie = await portal.start({ uid: account.uid, auth_time: Math.floor(Date.now() / 1000) });
  let ticket;
  const response = { writeHead() {}, end(body) { ticket = /name="ticket" value="([^"]+)"/.exec(body)[1]; } };
  await portal.launch(response, 'terminal-admin', cookie, () => portal.user(cookie));
  const results = await Promise.allSettled([verifier.exchange(ticket), portal.exchange(ticket)]);
  const successes = results.filter(result => result.status === 'fulfilled');
  assert.equal(successes.length, 1);
  assert.equal(results.find(result => result.status === 'rejected').reason.status, 401);
  const { handle, entry } = successes[0].value;
  assert.equal(entry, '/admin');
  await verifier.check(handle, 'terminal-admin');
  await auth.setCustomUserClaims(account.uid, { role: 'staff' });
  await assert.rejects(verifier.check(handle, 'terminal-admin'), { status: 403 });
  await verifier.check(handle, 'terminal');
  await auth.updateUser(account.uid, { disabled: true });
  await assert.rejects(verifier.check(handle, 'terminal'), { status: 403 });
  await auth.updateUser(account.uid, { disabled: false });
  await portal.launch(response, 'terminal', cookie, () => portal.user(cookie));
  await portal.forget(cookie);
  await assert.rejects(verifier.exchange(ticket), { status: 401 });
  await assert.rejects(verifier.check(handle, 'terminal'), { status: 401 });
});
